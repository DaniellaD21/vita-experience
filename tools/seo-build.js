function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
function textEsc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
function ld(obj) { return '<script type="application/ld+json">' + JSON.stringify(obj).replace(/</g, '\\u003c') + '</script>'; }

function hreflangLinks() {
  return ['es', 'en', 'he'].map(function (k) { return '<link rel="alternate" hreflang="' + k + '" href="' + META[k].url + '">'; })
    .concat('<link rel="alternate" hreflang="x-default" href="' + META.es.url + '">').join('\n');
}

function headBlock(l) {
  const m = META[l];
  const alt = Object.keys(META).filter(function (k) { return k !== l; }).map(function (k) { return '<meta property="og:locale:alternate" content="' + META[k].locale + '">'; }).join('\n');
  return [
    '<!-- seo:start · generated by tools/seo-build.js -->',
    '<title>' + textEsc(m.title) + '</title>',
    '<meta name="description" content="' + esc(m.desc) + '">',
    '<meta name="robots" content="index,follow,max-image-preview:large">',
    '<link rel="canonical" href="' + m.url + '">',
    hreflangLinks(),
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="Vita Experience">',
    '<meta property="og:url" content="' + m.url + '">',
    '<meta property="og:title" content="' + esc(m.ogTitle) + '">',
    '<meta property="og:description" content="' + esc(m.desc) + '">',
    '<meta property="og:image" content="' + SITE + '/og.jpg">',
    '<meta property="og:locale" content="' + m.locale + '">',
    alt,
    '<meta name="twitter:card" content="summary_large_image">',
    ld(ORG),
    '<!-- seo:end -->',
  ].join('\n');
}

function readObject(html, marker) {
  const s = html.indexOf(marker);
  if (s < 0) throw new Error(marker + ' not found');
  let i = html.indexOf('{', s), d = 0, j = i, q = null;
  for (; j < html.length; j++) {
    const c = html[j];
    if (q) { if (c === '\\') j++; else if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === '`') q = c;
    else if (c === '{') d++;
    else if (c === '}') { d--; if (!d) break; }
  }
  return (0, eval)('(' + html.slice(i, j + 1) + ')');
}

function buildHome(src, l, I) {
  let h = src;
  h = h.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->\n?/, '');
  h = h.replace(/<title>[^<]*<\/title>\n?/, '');
  h = h.replace(/<meta name="description"[^>]*>\n?/, '');
  h = h.replace(/<meta name="twitter:card"[^>]*>\n?/, '');
  h = h.replace(/<link rel="canonical"[^>]*>\n?/, '');
  h = h.replace(/<meta property="og:(type|site_name|url|title|description|image)"[^>]*>\n?/g, '');
  h = h.replace(/<base href="\/">\n?/, '');
  h = h.replace(/<script>window\.VX_LANG=[^<]*<\/script>\n?/, '');
  let extra = headBlock(l);
  if (l !== 'es') extra = '<base href="/">\n<script>window.VX_LANG=' + JSON.stringify(l) + '</script>\n' + extra;
  h = h.replace(/(<meta charset="utf-8">\n)/, '$1' + extra + '\n');
  h = h.replace(/<html[^>]*>/, '<html lang="' + l + '"' + (l === 'he' ? ' dir="rtl"' : '') + '>');
  const dict = I[l];
  h = h.replace(/(data-i18n="([\w-]+)"[^>]*>)([^<]*)(<)/g, function (all, open, k, _old, lt) {
    const v = dict[k] != null ? dict[k] : I.es[k];
    if (v == null || /\{\w+\}/.test(v)) return all;
    return open + textEsc(v) + lt;
  });
  h = h.replace(/(<input\b[^>]*?data-i18n-ph="([\w-]+)")([^>]*>)/g, function (all, a, k, b) {
    const v = dict[k] != null ? dict[k] : I.es[k];
    if (v == null) return all;
    const tag = (a + b).replace(/\splaceholder="[^"]*"/, '');
    return tag.replace(/data-i18n-ph="[\w-]+"/, function (x) { return x + ' placeholder="' + esc(v) + '"'; });
  });
  return h;
}

function buildCatalog(src) {
  const T = readObject(src, 'const T={');
  let h = src;
  // FAQ as real HTML (Spanish; JavaScript still switches language).
  const items = T.es.faq.map(function (q) { return '<details><summary>' + textEsc(q[0]) + '</summary><p>' + textEsc(q[1]) + '</p></details>'; }).join('');
  h = h.replace(/(<div class="faq reveal" id="faqList">)[\s\S]*?(<\/div>)/, '$1' + items + '$2');
  // FAQPage data in Spanish and English.
  const faq = {
    '@context': 'https://schema.org', '@type': 'FAQPage', '@id': SITE + '/catalogo#faq',
    mainEntity: [].concat(
      T.es.faq.map(function (q) { return { '@type': 'Question', inLanguage: 'es', name: q[0], acceptedAnswer: { '@type': 'Answer', text: q[1] } }; }),
      T.en.faq.map(function (q) { return { '@type': 'Question', inLanguage: 'en', name: q[0], acceptedAnswer: { '@type': 'Answer', text: q[1] } }; })
    ),
  };
  h = h.replace(/<!-- seo:faq -->[\s\S]*?<!-- \/seo:faq -->\n?/, '');
  h = h.replace(/<\/head>/, '<!-- seo:faq -->' + ld(faq) + '<!-- /seo:faq -->\n</head>');
  return h;
}

